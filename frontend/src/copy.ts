export type CopyKey = keyof typeof COPY;

/** Lấy copy theo key và thay biến `{x}`. Biến thiếu giữ nguyên `{x}` để dễ phát hiện khi review. */
export function t(key: CopyKey, vars: Record<string, string | number> = {}): string {
  return COPY[key].replace(/\{(\w+)\}/g, (all, name: string) =>
    name in vars ? (typeof vars[name] === 'number' ? (vars[name] as number).toLocaleString('vi-VN') : String(vars[name])) : all
  );
}

/** Danh sách số `unsupported`: nối ", ", tối đa 3 mục rồi "…" (3c). */
export function joinNums(nums: string[]): string {
  return nums.length > 3 ? nums.slice(0, 3).join(', ') + ', …' : nums.join(', ');
}
